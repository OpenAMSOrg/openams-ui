// Import specifier rewriting for the Mainsail generator.
//
// The panel lands at a different depth in the Mainsail fork than its sources
// sit at in openams-ui, so a relative specifier that reaches web/logic or
// web/vue has to be re-aimed at the generated tree. Nothing else about a
// specifier changes, and non-relative specifiers are left alone.

import { posix } from 'node:path'

// `from '…'`, `import '…'`, `import('…')`, `require('…')`, and the scss
// `@use` / `@forward` / `@import`. One regex, not two: `@import` also matches
// the bare `import` branch, and two passes over the same text would each cut
// the same span. The quote is captured so a quote of the same kind inside the
// specifier is skipped.
const SPECIFIER = /(?:\bfrom|\bimport|\brequire|@(?:use|forward|import))\s*\(?\s*(['"])((?:\\.|(?!\1)[^\\])*)\1/g

/**
 * Blanks out comments and string bodies (newlines kept, so offsets survive)
 * so a specifier-looking word in a comment is never rewritten. The returned
 * text has the same length as the input.
 */
function maskInert(src) {
  const out = src.split('')
  let i = 0
  while (i < src.length) {
    const c = src[i]
    if (c === '/' && src[i + 1] === '/') {
      while (i < src.length && src[i] !== '\n') out[i++] = ' '
    } else if (c === '/' && src[i + 1] === '*') {
      const close = src.indexOf('*/', i + 2)
      const stop = close === -1 ? src.length : close + 2
      for (let k = i; k < stop; k++) if (src[k] !== '\n' && src[k] !== '\r') out[k] = ' '
      i = stop
    } else if (c === '"' || c === "'" || c === '`') {
      i++
      while (i < src.length && src[i] !== c) i += src[i] === '\\' ? 2 : 1
      i++
    } else {
      i++
    }
  }
  return out.join('')
}

/** The `.ts` a bundler resolution does not want. Other extensions stay. */
function stripTs(specifier) {
  return specifier.endsWith('.ts') ? specifier.slice(0, -3) : specifier
}

/** `a/b/c` seen from `a/x` -> `./c`; always prefixed with `./` or `../`. */
export function relativeSpecifier(fromDir, to) {
  const a = fromDir === '' ? [] : fromDir.split('/')
  const b = to.split('/')
  let shared = 0
  while (shared < a.length && shared < b.length - 1 && a[shared] === b[shared]) shared++
  const up = a.slice(shared).map(() => '..')
  const rel = [...up, ...b.slice(shared)].join('/') || '.'
  return rel.startsWith('.') ? rel : `./${rel}`
}

/**
 * Re-aims every relative specifier in `text` that resolves into one of `map`
 * (longest prefix first), and drops a trailing `.ts` from the rest.
 *
 * @param srcDir   the source file's directory, relative to the repo root
 * @param destFile the destination file, relative to the --out root
 * @param map      [{ prefix, dest }], repo-relative source prefix -> out-relative
 * @param aliases  { '@logic': 'out/relative/dest' }: a non-relative specifier
 *                 the source tree's bundler resolves (web/vue's vite alias),
 *                 re-aimed at a file or folder of the output
 */
export function rewriteImports(text, { srcDir, destFile, map, aliases = {} }) {
  const masked = maskInert(text)
  const fromDir = posix.dirname(destFile)
  const edits = []
  SPECIFIER.lastIndex = 0
  let m
  while ((m = SPECIFIER.exec(masked)) !== null) {
    const start = m.index + m[0].length - 1 - m[2].length
    edits.push({ start, end: start + m[2].length, spec: m[2] })
  }
  let out = text
  // Back to front: an edit changes the length of what follows it.
  for (const e of edits.sort((x, y) => y.start - x.start)) {
    const next = rewriteOne(e.spec, { srcDir, fromDir, map, aliases })
    if (next === null) continue
    out = out.slice(0, e.start) + next + out.slice(e.end)
  }
  return out
}

function rewriteOne(spec, { srcDir, fromDir, map, aliases }) {
  for (const [alias, dest] of Object.entries(aliases)) {
    if (spec === alias) return stripTs(relativeSpecifier(fromDir, dest))
    if (spec.startsWith(`${alias}/`)) return stripTs(relativeSpecifier(fromDir, dest + spec.slice(alias.length)))
  }
  if (!spec.startsWith('.')) return null
  const resolved = posix.normalize(posix.join(srcDir, spec))
  for (const { prefix, dest } of map) {
    if (resolved !== prefix && !resolved.startsWith(`${prefix}/`)) continue
    return stripTs(relativeSpecifier(fromDir, dest + resolved.slice(prefix.length)))
  }
  return stripTs(spec)
}

// A file that calls itself generated, before any code. A source tree's own
// banner names a tool the fork has never heard of, and the fork is meant to
// read as ordinary source.
const BANNER = /^\s*(\/\/|\/\*|\*)[^\n]*(generated by|autogenerated|do not edit)/i

export function stripGeneratedBanner(text) {
  const lines = text.split('\n')
  let i = 0
  while (i < lines.length && lines[i].trim() === '') i++
  if (i >= lines.length || !BANNER.test(lines[i])) return text
  lines.splice(i, 1)
  if (lines[i] !== undefined && lines[i].trim() === '') lines.splice(i, 1)
  return lines.join('\n')
}

// `@use '<path>' as *;`, the one form the panel's scoped SCSS uses.
const SCSS_USE_AS_STAR = /@use\s+(['"])((?:\\.|(?!\1)[^\\])*)\1\s+as\s+\*;/g

/**
 * `@use '<path>' as *` to `@import '<path>'`, for a host whose bundler injects
 * its own `@import` at the top of every SCSS block: sass insists a `@use`
 * comes before any other rule, and the injection puts it second. The two mean
 * the same thing here — `as *` already puts every member in the current file's
 * namespace — and the host that injects an `@import` is a host that has
 * silenced its deprecation.
 */
export function scssUseAsImport(text) {
  return text.replace(SCSS_USE_AS_STAR, "@import $1$2$1;")
}
