#!/usr/bin/env node
// Generates the fixed user-facing strings for both cores from
// design/strings/<lang>.json (PRINCIPLES.md 5: one vocabulary, composed in one
// place). en.json is the master: it holds every id, in order, and every other
// language falls back to it for the ids it leaves out.
//
//   src/view/strings_ids.gen.h    the VS_* enum body        (included by strings.h)
//   src/view/strings_langs.gen.h  VS_LANG_<CODE> 1 or 0 per language, and
//                                 VS_LANG_COUNT: which languages this build
//                                 carries     (included by strings_table.gen.h
//                                 and by src/ui/ui_fonts_lang.c)
//   src/view/strings_table.gen.h  one const table per language, the codes and
//                                 each language's own name  (included by strings.c)
//   src/view/strings_keys.gen.h   the host setting keys      (included by strings.c)
//   web/logic/strings.gen.ts      the same tables for the TypeScript core
//
//   node tools/gen_strings.mjs           write the files
//   node tools/gen_strings.mjs --check   fail when a generated file is stale, a
//                                        language has an id English has not, or
//                                        a placeholder set that differs
//   node tools/gen_strings.mjs --pseudo  rewrite design/strings/qps.json from
//                                        English (the pseudo-locale)

import { readFileSync, writeFileSync, existsSync, readdirSync } from 'node:fs';
import { dirname, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const STRING_DIR = resolve(root, 'design/strings');
const MASTER = 'en';
const PSEUDO = 'qps';
const HEADER = 'Generated by tools/gen_strings.mjs from design/strings/<lang>.json. Do not edit.';

/** A C string literal. Non-ASCII bytes are octal escapes: three digits, so the
 *  next character can never be swallowed the way a \x escape swallows hex digits. */
function cLiteral(text) {
  let out = '"';
  for (const byte of Buffer.from(text, 'utf8')) {
    const ch = String.fromCharCode(byte);
    if (byte >= 0x80 || byte < 0x20) out += '\\' + byte.toString(8).padStart(3, '0');
    else if (ch === '"' || ch === '\\') out += '\\' + ch;
    else out += ch;
  }
  return out + '"';
}

export { cLiteral };

/** A language code turned into an identifier fragment. A code carries its
 *  region ("pt-BR"), and a hyphen is not legal in a C or a TypeScript name, so
 *  it becomes an underscore there. The code itself is untouched everywhere it
 *  is a value - LANG_CODES, the k_lang_code table, the TABLES keys - so
 *  setLanguage("pt-BR") still finds its table. */
const ident = (code) => code.replace(/[^A-Za-z0-9_]/g, '_');

/* ------------------------------------------------------------------ load */

/** One design/strings/<code>.json: its code, its own name (never translated -
 *  the language list shows "Deutsch" and "日本語" whatever the UI language), its
 *  ids in file order, and its group comments (for the generated headers). */
function loadLanguage(code) {
  const file = resolve(STRING_DIR, `${code}.json`);
  if (!existsSync(file)) return null;
  const doc = JSON.parse(readFileSync(file, 'utf8'));
  // "<ID>@<case>" is a case form of ID (see genTables): not an id of its own.
  const entries = doc.strings.filter((e) => e.id && !e.id.includes('@'));
  const forms = doc.strings.filter((e) => e.id && e.id.includes('@')).map((e) => {
    const at = e.id.indexOf('@');
    return { base: e.id.slice(0, at), kase: e.id.slice(at + 1), text: e.text };
  });
  const groups = doc.strings.filter((e) => e.group);
  return {
    code: doc.code ?? code,
    name: doc.name ?? code,
    ids: entries.map((e) => e.id),
    text: new Map(entries.map((e) => [e.id, e.text])),
    forms,
    groups,
    settingKeys: doc.setting_keys ?? [],
  };
}

/** English first, the real languages in file-name order, the pseudo-locale
 *  last: en.json owns the enum, the TS key order and the fallback, and qps at
 *  the end keeps a language's index equal to its place in the language list
 *  (which leaves qps out). glossary.json sits in the same directory but holds
 *  no table, so it is not a language. */
function loadLanguages() {
  const files = readdirSync(STRING_DIR)
    .filter((f) => f.endsWith('.json') && f !== 'glossary.json')
    .map((f) => f.slice(0, -5));
  const codes = [MASTER, ...files.filter((c) => c !== MASTER && c !== PSEUDO).sort(),
    ...files.filter((c) => c === PSEUDO)];
  const langs = codes.map(loadLanguage);
  if (!langs[0]) throw new Error(`gen_strings: ${MASTER}.json is missing from design/strings/`);
  return langs;
}

/* ------------------------------------------------------------- placeholders */

/** The tokens a translation must keep: every `{field}` and every printf
 *  conversion, in the order they appear. Two languages may not disagree on this
 *  set, or a translated action line/form would reach the mapper differently. */
function placeholders(text) {
  // "{spool@acc}" is still the placeholder "{spool}", asked for in a case.
  return [...text.matchAll(/\{[^{}]*\}|%[-+ #0-9.*']*(?:hh|h|ll|l|z)?[diouxXeEfgGaAcspn%]/g)]
    .map((m) => m[0].replace(/@[^{}]*\}$/, '}'));
}

/* ------------------------------------------------------------------ pseudo */

/* One accented stand-in per ASCII letter, so a translation that is too short
 * or in the wrong font shows up in review. */
const ACCENT = {
  a: 'á', b: 'ƀ', c: 'ç', d: 'ď', e: 'é', f: 'ƒ', g: 'ğ', h: 'ĥ', i: 'í', j: 'ĵ', k: 'ķ',
  l: 'ļ', m: 'ɱ', n: 'ñ', o: 'ô', p: 'ƥ', q: 'ɋ', r: 'ŕ', s: 'š', t: 'ť', u: 'ú', v: 'ṽ',
  w: 'ŵ', x: 'ẋ', y: 'ý', z: 'ž',
  A: 'Á', B: 'Ɓ', C: 'Ç', D: 'Ď', E: 'É', F: 'Ƒ', G: 'Ğ', H: 'Ĥ', I: 'Í', J: 'Ĵ', K: 'Ķ',
  L: 'Ĺ', M: 'Ṁ', N: 'Ñ', O: 'Ô', P: 'Ƥ', Q: 'Ɋ', R: 'Ŕ', S: 'Š', T: 'Ť', U: 'Ú', V: 'Ṽ',
  W: 'Ŵ', X: 'Ẋ', Y: 'Ý', Z: 'Ž',
};
const ELLIPSIS = '…';   // the padding, so the growth is visible at a glance

/** English -> the pseudo-locale: accented letters, brackets marking the start
 *  and the end, and about 40% more characters, which is the growth a real
 *  translation is expected to bring (i18n-b's length budgets). A `{field}`
 *  token or a printf conversion is copied through untouched; every other
 *  character is accented, literal text included, so a whole-sentence template
 *  is padded whole and the length budget it produces is the real one. A string
 *  with no letter to accent ("?", "∞") is left alone: there is nothing to make
 *  longer. */
export function pseudoText(text) {
  if (!/[A-Za-z]/.test(text)) return text;
  let out = '';
  for (let i = 0; i < text.length; ) {
    const token = /^\{[^{}]*\}|^%[-+ #0-9.*']*(?:hh|h|ll|l|z)?[diouxXeEfgGaAcspn%]/.exec(text.slice(i));
    if (token) { out += token[0]; i += token[0].length; continue; }
    out += ACCENT[text[i]] ?? text[i];
    i++;
  }
  const pad = Math.max(2, Math.floor(text.length * 0.4));
  return `[${out}${ELLIPSIS.repeat(pad)}]`;
}

/* ------------------------------------------------------------- C and TS */

/** The VS_* enum body, English's ids in English's order: every language
 *  compiles against the same enum, and an id the current language has no text
 *  for falls back to English's entry. */
function genIds(master) {
  const lines = [`/* ${HEADER} */`];
  for (const g of master.groups) lines.push('', `    /* ${g.group} */`);
  for (const id of master.ids) lines.push(`    VS_${id},`);
  return lines.join('\n') + '\n';
}

/** Which languages this build carries, as VS_LANG_<CODE> 1 or 0, and
 *  VS_LANG_COUNT as their sum. cmake/languages.cmake defines MMU_LANG_SELECTED
 *  and one MMU_LANG_<code> per language when the build picks a set; with none
 *  defined every language is built in, so this header stands on its own and the
 *  host builds, the wasm core and the tests keep every language.
 *
 *  Its own file, not part of strings_table.gen.h, because the CJK face list
 *  (src/ui/ui_fonts_lang.c) answers the same question and must not pull in the
 *  whole catalog to do it.
 *
 *  The pseudo-locale is for tests and layout review, so VIEW_NO_PSEUDO still
 *  leaves it out (the device images), as does a set that does not name it. */
function genLangs(langs) {
  // The macro names are upper case ("pt-BR" -> PT_BR); the table names keep
  // the code's own case (k_table_pt_BR).
  const macro = (code) => `VS_LANG_${ident(code).toUpperCase()}`;
  const pick = (code) => `MMU_LANG_${ident(code).toUpperCase()}`;
  const out = [`/* ${HEADER} */`, ''];
  for (const lang of langs) {
    // VIEW_NO_PSEUDO wins over MMU_LANG_QPS: a device build asks for neither.
    const chosen = `defined(${pick(lang.code)}) || !defined(MMU_LANG_SELECTED)`;
    const when = lang.code === PSEUDO ? `!defined(VIEW_NO_PSEUDO) && (${chosen})` : chosen;
    out.push(`#if ${when}`, `#define ${macro(lang.code)} 1`, '#else',
      `#define ${macro(lang.code)} 0`, '#endif', '');
  }
  out.push('/* Every language the repository has, built in or not: lets a tool tell a',
    ' * code this build left out from one that does not exist at all. */');
  out.push(`#define VS_KNOWN_LANG_CODES ${langs.map((l) => cLiteral(l.code)).join(', ')}`, '');
  out.push('/* The languages built in, English first: what view_lang_count() is. */');
  out.push(`#define VS_LANG_COUNT (${langs.map((l) => macro(l.code)).join(' + ')})`);
  return out.join('\n') + '\n';
}

/** One const table per language, in flash (const data), plus the language
 *  codes and each language's own name. An id the language leaves out stays
 *  NULL, which is what view_str()'s fallback to English keys on.
 *
 *  A table, and an entry of any of the three lists, sits behind its
 *  VS_LANG_<CODE>, so a build that does not carry a language pays for none of
 *  it. */
function genTables(langs) {
  const guard = (l, lines) => [`#if VS_LANG_${ident(l.code).toUpperCase()}`, ...lines, '#endif'];
  const list = (decl, entry) =>
    [`static const char *const ${decl}[VS_LANG_COUNT] = {`, ...langs.flatMap((l) => guard(l, [`    ${entry(l)},`])), '};'].join('\n');
  const out = [`/* ${HEADER} */`, '', '#include "view/strings_langs.gen.h"'];
  for (const lang of langs) {
    const table = [`static const char *const k_table_${ident(lang.code)}[VS_COUNT] = {`];
    for (const g of lang.groups) table.push(`    /* ${g.group} */`);
    for (const id of lang.ids) table.push(`    [VS_${id}] = ${cLiteral(lang.text.get(id))},`);
    table.push('};');
    out.push('', `/* ${lang.code} */`, ...guard(lang, table));
  }
  out.push('', '/* Each language by its own name, whatever the UI language is showing. */');
  out.push(list('k_lang_code', (l) => cLiteral(l.code)));
  out.push(list('k_lang_name', (l) => cLiteral(l.name)));
  out.push(list('*const k_tables', (l) => `k_table_${ident(l.code)}`));

  // Case forms. A language whose nouns change with their role gives the forms
  // of a placeholder's own text ("SPOOL_LABEL@acc": "Катушку {n}"), and its
  // templates ask for one ("Сбросить {spool@acc}?"). vs_format() matches the
  // placeholder's text against the base template and rebuilds it in the case.
  out.push('', '/* Case forms per language: {base id, case, text}, ended by id -1. */');
  out.push('typedef struct { int id; const char *kase; const char *text; } vs_form_t;');
  for (const lang of langs.filter((l) => l.forms.length)) {
    const rows = lang.forms.map((f) => `    { VS_${f.base}, ${cLiteral(f.kase)}, ${cLiteral(f.text)} },`);
    out.push(...guard(lang, [`static const vs_form_t k_forms_${ident(lang.code)}[] = {`, ...rows, '    { -1, NULL, NULL },', '};']));
  }
  out.push('static const vs_form_t *const k_forms[VS_LANG_COUNT] = {',
    ...langs.flatMap((l) => guard(l, [`    ${l.forms.length ? `k_forms_${ident(l.code)}` : 'NULL'},`])), '};');
  return out.join('\n') + '\n';
}

/** The host's setting keys, in the order of the settings rows. */
function genKeys(master) {
  return [`/* ${HEADER} */`, '', `#define VIEW_SETTING_KEY_COUNT ${master.settingKeys.length}`,
    '', 'static const char *const k_setting_key[VIEW_SETTING_KEY_COUNT] = {',
    ...master.settingKeys.map((k) => `    ${cLiteral(k)},`), '};'].join('\n') + '\n';
}

/** The same tables for the TypeScript core: one object per language (a
 *  language that leaves an id out simply has no key, and str() falls back to
 *  English), plus the codes and the names. */
function genTs(langs, master) {
  const out = [
    `// ${HEADER}`,
    '',
    '/** English: the master table, with every id. */',
    `export const STR_${MASTER} = {`,
    ...master.ids.map((id) => `  ${id}: ${JSON.stringify(master.text.get(id))},`),
    '} as const;',
    '',
    `export type StrId = keyof typeof STR_${MASTER};`,
    '',
  ];
  for (const lang of langs.filter((l) => l.code !== MASTER)) {
    out.push(`/** ${lang.code}: only the ids it translates; the rest fall back to English. */`);
    out.push(`export const STR_${ident(lang.code)}: Partial<Record<StrId, string>> = {`);
    for (const id of lang.ids) out.push(`  ${id}: ${JSON.stringify(lang.text.get(id))},`);
    out.push('};', '');
  }
  out.push('/** Case forms, by language: [base id, case, text] (see strings.ts format()). */');
  out.push('export const FORMS: Record<string, ReadonlyArray<readonly [StrId, string, string]>> = {');
  for (const lang of langs.filter((l) => l.forms.length)) {
    out.push(`  ${cLiteral(lang.code)}: [`);
    for (const f of lang.forms) out.push(`    [${JSON.stringify(f.base)}, ${JSON.stringify(f.kase)}, ${JSON.stringify(f.text)}],`);
    out.push('  ],');
  }
  out.push('};', '');
  out.push('/** Every language table, keyed by code, English first. */');
  out.push('export const TABLES: Record<string, Partial<Record<StrId, string>>> = {');
  for (const lang of langs) out.push(`  ${cLiteral(lang.code)}: STR_${ident(lang.code)},`);
  out.push('};', '');
  out.push('/** The language codes, in table order. */');
  out.push(`export const LANG_CODES = ${JSON.stringify(langs.map((l) => l.code))} as const;`);
  out.push('');
  out.push('/** Each language by its own name, in the same order. */');
  out.push(`export const LANG_NAMES = ${JSON.stringify(langs.map((l) => l.name))} as const;`);
  out.push('');
  out.push('/** The host\'s setting keys, in the order of the settings rows. */');
  out.push(`export const SETTING_KEYS = ${JSON.stringify(master.settingKeys)} as const;`);
  out.push('');
  return out.join('\n');
}

/* ----------------------------------------------------------------- checks */

/** Everything --check refuses: a stale generated file, a language with an id
 *  English has not, and a translation that changed a placeholder set. */
function checkLanguages(langs, master) {
  const problems = [];
  for (const lang of langs) {
    if (lang.code === MASTER) continue;
    for (const id of lang.ids) {
      if (!master.text.has(id)) {
        problems.push(`${lang.code}: "${id}" is not an id of ${MASTER}.json`);
        continue;
      }
      const want = placeholders(master.text.get(id)).sort().join(' ');
      const got = placeholders(lang.text.get(id) ?? '').sort().join(' ');
      if (want !== got) {
        problems.push(`${lang.code}: "${id}" placeholders [${got}] differ from English's [${want}]`);
      }
    }
    for (const f of lang.forms) {
      if (!master.text.has(f.base)) {
        problems.push(`${lang.code}: "${f.base}@${f.kase}" is a form of no id of ${MASTER}.json`);
        continue;
      }
      if (!/^[a-z]+$/.test(f.kase)) problems.push(`${lang.code}: "${f.base}@${f.kase}": a case is lowercase letters`);
      const want = placeholders(master.text.get(f.base)).sort().join(' ');
      const got = placeholders(f.text).sort().join(' ');
      if (want !== got) {
        problems.push(`${lang.code}: "${f.base}@${f.kase}" placeholders [${got}] differ from English's [${want}]`);
      }
    }
    const keys = lang.settingKeys.join(',');
    if (lang.settingKeys.length && keys !== master.settingKeys.join(',')) {
      problems.push(`${lang.code}: setting_keys differ from English's`);
    }
  }
  return problems;
}

/* ------------------------------------------------------------------ main */

const args = process.argv.slice(2);

if (args.includes('--pseudo')) {
  // The pseudo-locale is derived, never hand-edited: it is regenerated from
  // English whenever English changes, so it can never drift. It is written
  // before the tables are read, so the same run also generates its C and TS
  // tables.
  const doc = JSON.parse(readFileSync(resolve(STRING_DIR, `${MASTER}.json`), 'utf8'));
  doc.$comment = 'The pseudo-locale: generated from en.json by `node tools/gen_strings.mjs --pseudo`, never hand-edited. It exists so the layout, the fonts and the truncation can be reviewed in a language longer than English; the real translations arrive in their own files (i18n-b).';
  doc.code = PSEUDO;
  doc.name = 'Pseudo-locale';
  // An id the pseudo-locale does not change is left out, the way a translator
  // leaves out what they have not translated yet: the view falls back to
  // English for it, so the table stays the set of strings this language
  // actually has. "?" and "∞" have no letter to accent and are exactly those.
  doc.strings = doc.strings
    .filter((e) => !e.id || pseudoText(e.text) !== e.text)
    .map((e) => (e.id ? { ...e, text: pseudoText(e.text) } : e));
  writeFileSync(resolve(STRING_DIR, `${PSEUDO}.json`), `${JSON.stringify(doc, null, 1)}\n`);
  console.log('wrote', `design/strings/${PSEUDO}.json`);
}

const langs = loadLanguages();
const master = langs[0];
const problems = checkLanguages(langs, master);
if (problems.length) {
  for (const p of problems) console.error(`gen_strings: ${p}`);
  process.exit(1);
}

const outputs = {
  'src/view/strings_ids.gen.h': genIds(master),
  'src/view/strings_langs.gen.h': genLangs(langs),
  'src/view/strings_table.gen.h': genTables(langs),
  'src/view/strings_keys.gen.h': genKeys(master),
  'web/logic/strings.gen.ts': genTs(langs, master),
};

const check = args.includes('--check');
let stale = 0;
for (const [path, text] of Object.entries(outputs)) {
  const file = resolve(root, path);
  if (check) {
    if (!existsSync(file) || readFileSync(file, 'utf8') !== text) {
      console.error('stale:', path);
      stale++;
    }
  } else {
    writeFileSync(file, text);
    console.log('wrote', path);
  }
}
if (check) {
  if (stale) {
    console.error('run: node tools/gen_strings.mjs');
    process.exit(1);
  }
  console.log(`strings: ${langs.length} languages, generated files are current`);
}
