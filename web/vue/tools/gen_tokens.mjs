#!/usr/bin/env node
// Generates the Vue renderer's design tokens from design/tokens.json
// (docs/design/UNIFIED_UI.md 5, 6), the way tools/gen_tokens.mjs does for the
// Lit renderer.
//
//   node tools/gen_tokens.mjs   writes web/vue/src/tokens.scss and src/tokens.css
//
// Structure: resolveTokens() turns the JSON into a renderer-neutral model
// (named values per theme); each output is an emitter over that model. The
// components' scoped SCSS uses tokens.scss (the shared values and a few
// mixins), and the themes' custom properties reach the elements at runtime
// through tokens.css, so a host's colors and fonts cascade in (the host sets
// --oams-accent and friends, never the component's SCSS).

import { readFileSync, writeFileSync, mkdirSync } from 'node:fs';
import { dirname, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const tokens = JSON.parse(readFileSync(resolve(root, '../../design/tokens.json'), 'utf8'));

// The host theme (docs/design/UNIFIED_UI.md 6): the card is the host's, so the
// surfaces and the line are foreground alphas over it, and text and the UI
// font inherit. The heat scale stays ours; they use mid-tone
// values that read on a dark and on a light card.
const HOST_COLORS = {
  ...tokens.color.host,
  // The wrapper sets these from the host's palette; these are the fallbacks
  // (the status colors that are text are in the host block, mixed with the card's text).
  accent: tokens.color.light.accent,
  ok: tokens.color.light.ok,
  info: tokens.color.light.info,
};

function resolveTokens(t) {
  const themes = {
    dark: { ...t.color.dark },
    light: { ...t.color.light },
    host: { ...HOST_COLORS },
  };
  const ui = `"${t.font.ui}", ui-sans-serif, system-ui, sans-serif`;
  const mono = 'ui-monospace, "Roboto Mono", monospace';
  const monoStandalone = `"${t.font.mono}", ${mono}`;
  return {
    themes,
    // undefined in the host theme: the component falls back to `inherit`.
    fonts: { host: { mono }, dark: { ui, mono: monoStandalone }, light: { ui, mono: monoStandalone } },
    radius: t.radius,
    hatch: t.hatch,
    space: t.space,
    type: t.type.web,
    tile: t.tile,
  };
}

// ---- emitters -------------------------------------------------------------

/** The shared custom properties: radii, gaps, the hatch, the type scale. */
function sharedDecls(m) {
  const d = [];
  for (const [k, v] of Object.entries(m.radius)) d.push([`--oams-radius-${k}`, `${v}px`]);
  for (const [k, v] of Object.entries(m.space)) if (typeof v === 'number') d.push([`--oams-gap-${k}`, `${v}px`]);
  d.push(['--oams-hatch-angle', `${m.hatch.angle}deg`], ['--oams-hatch-period', `${m.hatch.period}px`],
    ['--oams-hatch-stripe', `${m.hatch.stripe}px`]);
  for (const [k, [size, weight]] of Object.entries(m.type)) {
    d.push([`--oams-fs-${k}`, `${size}px`], [`--oams-fw-${k}`, String(weight)]);
  }
  d.push(['--oams-ink-threshold', String(m.tile.ink_threshold)]);
  return d;
}

function themeDecls(m, name) {
  // "$comment" (and any "$" key) in design/tokens.json is documentation, not a
  // token: emitted as a property it is invalid CSS, and its prose (an apostrophe
  // inside a parenthesis) swallows the declarations after it.
  const d = Object.entries(m.themes[name])
    .filter(([k]) => !k.startsWith('$'))
    .filter(([k]) => name !== 'host' || k !== 'text')
    .map(([k, v]) => [`--oams-${k}`, v]);
  d.push(['--oams-hatch-alpha', `${Math.round(m.hatch.alpha[name] * 100)}%`]);
  if (m.fonts[name].ui) d.push(['--oams-font-ui', m.fonts[name].ui]);
  d.push(['--oams-font-mono', m.fonts[name].mono]);
  return d;
}

const cssBlock = (selector, decls) => `${selector} {\n${decls.map(([k, v]) => `  ${k}: ${v};`).join('\n')}\n}\n`;

/** tokens.css: the themes as custom properties on the panel root. `host` is
 *  the default and the fallback for any other value, as in the Lit renderer. */
function emitCss(m) {
  return [
    '/* Generated by tools/gen_tokens.mjs from design/tokens.json. Do not edit. */\n',
    cssBlock('.oams-panel', [...sharedDecls(m), ...themeDecls(m, 'host')]),
    cssBlock('.oams-panel[data-theme="dark"]', themeDecls(m, 'dark')),
    cssBlock('.oams-panel[data-theme="light"]', themeDecls(m, 'light')),
  ].join('\n');
}

function emitScss(m) {
  const lines = ['// Generated by tools/gen_tokens.mjs from design/tokens.json. Do not edit.\n',
    '// The shared token values and the mixins the components\' scoped SCSS uses.',
    '// The themes themselves are CSS custom properties (tokens.css), so a host\'s',
    '// colors and fonts cascade in from outside.\n'];
  for (const [k, v] of Object.entries(m.radius)) lines.push(`$oams-radius-${k}: ${v}px;`);
  lines.push('');
  for (const [k, v] of Object.entries(m.space)) {
    if (typeof v === 'number') lines.push(`$oams-gap-${k}: ${v}px;`);
  }
  lines.push('');
  for (const [k, [size, weight]] of Object.entries(m.type)) {
    lines.push(`$oams-fs-${k}: ${size}px;`, `$oams-fw-${k}: ${weight};`);
  }
  lines.push('');
  lines.push(`$oams-hatch-angle: ${m.hatch.angle}deg;`, `$oams-hatch-period: ${m.hatch.period}px;`,
    `$oams-hatch-stripe: ${m.hatch.stripe}px;`);
  return lines.join('\n') + '\n' + MIXINS;
}

const MIXINS = `
/** The mono stack: the host's, or the standalone page's. */
@mixin oams-mono {
    font-family: var(--oams-font-mono);
}

/** A visible focus ring on every interactive element (principle 12). */
@mixin oams-focus {
    &:focus-visible {
        outline: 2px solid var(--oams-accent);
        outline-offset: 2px;
    }
}

/** The one disabled look: diagonal stripes of the text color over the
 *  surface, so "no spool" is never a black tile (docs/design/UNIFIED_UI.md 4c). */
@mixin oams-hatch {
    $stripe: color-mix(in srgb, var(--oams-text, currentColor) var(--oams-hatch-alpha), transparent);
    background: repeating-linear-gradient(
        $oams-hatch-angle,
        transparent 0,
        transparent calc(#{$oams-hatch-period} - #{$oams-hatch-stripe}),
        $stripe calc(#{$oams-hatch-period} - #{$oams-hatch-stripe}),
        $stripe $oams-hatch-period
    ),
        var(--oams-surface-3);
}
`;

const targets = [
  { path: 'src/tokens.css', emit: emitCss },
  { path: 'src/tokens.scss', emit: emitScss },
];

const model = resolveTokens(tokens);
for (const { path, emit } of targets) {
  const file = resolve(root, path);
  mkdirSync(dirname(file), { recursive: true });
  writeFileSync(file, emit(model));
  console.log('wrote', path);
}
